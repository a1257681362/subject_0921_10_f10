-- ============ papersel-1：教研组卷抽选（素材池 + 抽选算法三段式 + 多套并行抽选留痕） ============

-- ============ 题库素材（只下架不物理删除：增删改全部留台账；历史卷面对内容哈希做快照，池子变动不影响历史） ============
CREATE TABLE IF NOT EXISTS t_paper_material (
