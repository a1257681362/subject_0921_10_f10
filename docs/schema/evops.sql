-- ============ 等级规则模块（一个项目一套规则，规则下挂多个版本） ============
CREATE TABLE IF NOT EXISTS t_grade_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    -- 项目编码：与批次 project_code 对齐（助考等项目各管各的口径）
    project_code VARCHAR(32) NOT NULL,
    subject VARCHAR(128),
    -- 满分（各分数段须落在 [0, max_score]）
    max_score INT NOT NULL DEFAULT 100,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_grade_rule_code UNIQUE (code),
    CONSTRAINT ck_grade_rule_max CHECK (max_score > 0)
);

-- ============ 等级规则版本（卷面分按分数段落等级；发布后冻结，永不修改） ============
CREATE TABLE IF NOT EXISTS t_grade_rule_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    -- DRAFT 草稿 / ACTIVE 生效（同一规则同时刻仅一版；同项目可按科目各有一条规则） / DISABLED 停用
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    -- 分数段定义（发布时冻结的 JSON）：[{"minScore":0,"maxScore":60,"grade":"不合格"},...]
    -- 约定左闭右开 [minScore,maxScore)，段段相连不重叠不缺口，末段右端 = 满分
    grade_bands CLOB NOT NULL,
    remark VARCHAR(255),
    published_by VARCHAR(64),
    published_at TIMESTAMP,
    disabled_by VARCHAR(64),
    disabled_at TIMESTAMP,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_grade_rule_version_no UNIQUE (version_no)
);
CREATE INDEX IF NOT EXISTS idx_grade_version_rule ON t_grade_rule_version (rule_id);
CREATE INDEX IF NOT EXISTS idx_grade_version_project_status ON t_grade_rule_version (status);

-- ============ 成绩（一人一批次一条；定级时记下规则版本，口径可追溯） ============
CREATE TABLE IF NOT EXISTS t_exam_score (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    paper_score DECIMAL(6,2) NOT NULL,
    final_score DECIMAL(6,2),
    grade VARCHAR(16),
    -- 定级所用规则版本快照外键与版本号；规则版本停用/升级不影响历史口径
    rule_version_id BIGINT,
    rule_version_no VARCHAR(40),
    graded_at TIMESTAMP,
    -- RECORDED 已录入 / REVIEWING 复核中
    status VARCHAR(16) NOT NULL DEFAULT 'RECORDED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_score_registration UNIQUE (registration_id),
    CONSTRAINT ck_score_paper CHECK (paper_score >= 0)
);
CREATE INDEX IF NOT EXISTS idx_score_batch ON t_exam_score (batch_id);
CREATE INDEX IF NOT EXISTS idx_score_reg_no ON t_exam_score (reg_no);

-- ============ 成绩复核申请（窗口跟批次配置；超窗由定时任务自动关闭） ============
CREATE TABLE IF NOT EXISTS t_score_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    apply_reason VARCHAR(512),
    applicant VARCHAR(64),
    applied_at TIMESTAMP NOT NULL,
    -- SUBMITTED 待处理 / APPROVED 复核通过（改分） / REJECTED 复核驳回 / CLOSED 超窗自动关闭
    status VARCHAR(16) NOT NULL DEFAULT 'SUBMITTED',
    conclusion VARCHAR(512),
    reviewer VARCHAR(64),
    concluded_at TIMESTAMP,
    -- 结论时的改分前后快照，与改分日志互为印证
    score_before DECIMAL(6,2),
    grade_before VARCHAR(16),
    score_after DECIMAL(6,2),
    grade_after VARCHAR(16),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_review_batch ON t_score_review (batch_id);
CREATE INDEX IF NOT EXISTS idx_review_score ON t_score_review (score_id);
CREATE INDEX IF NOT EXISTS idx_review_status ON t_score_review (status);

