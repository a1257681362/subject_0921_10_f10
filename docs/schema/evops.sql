-- ============ 抽选算法版本（参数 JSON 发布即冻结；DRAFT/ACTIVE/DISABLED，同模块同时刻仅一版生效） ============
-- 事后公平核验时永久按卷面记录的版本号与冻结参数复算；算法升级不改变历史卷面口径。
CREATE TABLE IF NOT EXISTS t_paper_sel_algorithm_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    algorithm_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    -- DRAFT 草稿 / ACTIVE 生效 / DISABLED 停用
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    -- 发布时冻结的抽选参数 JSON：
    -- {"strategy":"KP_DIFFICULTY_QUOTA","maxOverlapRate":0.20,"maxRetries":50,"compareScope":"GROUP"}
    -- maxOverlapRate 套与套之间允许的最大重合率（重合素材数/单套题数）；超阈自动换种子重抽；
    -- maxRetries 单套自动重抽上限；compareScope=GROUP 仅与本次并行各套比对
    params CLOB NOT NULL,
    remark VARCHAR(255),
    published_by VARCHAR(64),
    published_at TIMESTAMP,
    disabled_by VARCHAR(64),
    disabled_at TIMESTAMP,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_paper_sel_version_no UNIQUE (version_no)
);
