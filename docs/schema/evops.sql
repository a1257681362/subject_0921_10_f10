-- ============ 混编算法模块（同校错开编排的算法定义，可按项目各建一套） ============
CREATE TABLE IF NOT EXISTS t_mix_algorithm (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    -- 项目编码：与批次 project_code 对齐；编排时取项目当前生效算法
    project_code VARCHAR(32) NOT NULL DEFAULT 'DEFAULT',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_mix_algorithm_code UNIQUE (code)
);

-- ============ 混编算法版本（参数 JSON 发布即冻结；DRAFT/ACTIVE/DISABLED，同模块同时刻仅一版生效） ============
CREATE TABLE IF NOT EXISTS t_mix_algorithm_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    algorithm_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    -- DRAFT 草稿 / ACTIVE 生效 / DISABLED 停用（被新版本顶替或人工停用）
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    -- 发布时冻结的算法参数 JSON：
    -- {"strategy":"SCHOOL_SPREAD","minSchoolGap":1,"maxSameSchoolPerRoom":null,"spreadRooms":true,"tries":40}
    -- minSchoolGap 同校学员在同考场内的最小座位间隔；spreadRooms 是否把同校按容量比例摊到多个考场
    params CLOB NOT NULL,
    remark VARCHAR(255),
    published_by VARCHAR(64),
    published_at TIMESTAMP,
    disabled_by VARCHAR(64),
    disabled_at TIMESTAMP,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_mix_algorithm_version_no UNIQUE (version_no)
);
CREATE INDEX IF NOT EXISTS idx_mix_version_algorithm ON t_mix_algorithm_version (algorithm_id);
CREATE INDEX IF NOT EXISTS idx_mix_version_status ON t_mix_algorithm_version (status);

-- ============ 编排记录（每次编排/整批重排一条：算法版本、随机种子、座次快照、同校相邻统计；只追加） ============
CREATE TABLE IF NOT EXISTS t_arrangement_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    -- ARRANGE 首次编排 / REARRANGE 整批重排
    run_type VARCHAR(16) NOT NULL,
    -- 本次使用的混编算法版本（算法/版本可追溯；无算法版本时为空，按顺序编排）
    mix_version_id BIGINT,
    mix_version_no VARCHAR(40),
    -- 洗牌随机种子：同种子同名册同考场可复现座次
    seed BIGINT NOT NULL,
    -- 座次快照 JSON：[{ticketNo,regNo,name,school,roomId,roomNo,seatNo},...]
    seating CLOB NOT NULL,
    total_count INT NOT NULL DEFAULT 0,
    room_count INT NOT NULL DEFAULT 0,
    -- 同校相邻对数（相邻=同考场座位号连续）；巡考抽查口径
    same_school_adjacent_count INT NOT NULL DEFAULT 0,
    -- 同校相邻明细 JSON：[{roomNo,seatA,seatB,school,nameA,nameB},...]
    adjacent_detail CLOB,
    -- 同批次同时刻仅一条当前编排；重排只切当前标记，旧记录保留
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    operator VARCHAR(64),
    executed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_arrangement_run_batch ON t_arrangement_run (batch_id);

